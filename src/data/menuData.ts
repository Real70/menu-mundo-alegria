export function getWhatsAppOrderUrl(item: {
  name: string;
  formattedPrice: string;
  serves?: string;
}): string {
  const portion = item.serves ? ` (${item.serves})` : '';
  const message = `¡Hola Restaurante Mundo Alegría! 👋 Deseo pedir: *${item.name}*${portion} - Precio: ${item.formattedPrice}.`;
  return `https://wa.me/${WHATSAPP_PHONE}?text=${encodeURIComponent(message)}`;
}

export function formatCOP(price: number): string {
  const clean = Math.max(0, Math.round(Number(price) || 0));
  return '$' + clean.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
}

export function slugify(text: string): string {
  return (
    text
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'item'
  );
}

